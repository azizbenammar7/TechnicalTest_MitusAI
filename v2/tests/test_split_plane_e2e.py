"""Split control-plane / data-plane end-to-end acceptance.

This is the headline P2.5 proof: the *real* AnalysisCoordinator, AnalysisExecutor
and API read path drive a full analysis through three independent providers --
PostgreSQL (control plane), Azure Blob via Azurite (data plane), and the local
filesystem queue (delivery) -- with no shared filesystem between the ingesting
"API" side and the executing "worker" side.

Runs only when both emulators are configured (``FOOTBALLAI_TEST_DATABASE_URL`` and
``FOOTBALLAI_TEST_BLOB_CONNECTION_STRING``); otherwise the whole module is
skipped so the fast deterministic suite never needs Docker. It uses tiny
generated byte payloads and the deterministic ``demo_fast`` / ``test_fail``
profiles -- never a real video or model.
"""

